"""Clean-clone install test: clone this repository into a NEW folder and set it up using only the documented steps
(setup.ps1 with -SkipHermes, so no Hermes profile is touched), then run tests, layout scan and doctor in the clone.

  python scripts/dev/clean_clone_test.py --dest <new empty folder> [--license student] [--python <py3.13 exe>]

Copies nothing machine-specific: the clone gets its own .venv and .local config generated by setup.
Prints a JSON summary. Not used by the agent.
"""
import argparse
import json
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]


def run(cmd, cwd, timeout=1800):
    r = subprocess.run(cmd, cwd=cwd, capture_output=True, text=True, timeout=timeout)
    return {"cmd": " ".join(map(str, cmd)), "rc": r.returncode, "tail": (r.stdout + r.stderr)[-1500:]}


def main() -> None:
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument("--dest", required=True)
    p.add_argument("--license", default="commercial", choices=["commercial", "student"])
    p.add_argument("--python", default="")
    a = p.parse_args()
    dest = Path(a.dest)
    if dest.exists() and any(dest.iterdir()):
        sys.exit(f"{dest} is not empty")
    steps = [run(["git", "clone", "--quiet", str(ROOT), str(dest)], cwd=ROOT.parent)]
    ps = ["powershell", "-NoProfile", "-ExecutionPolicy", "Bypass", "-File", "setup.ps1", "-License", a.license,
          "-SkipHermes"]
    if a.python:
        ps += ["-Python", a.python]
    steps.append(run(ps, cwd=dest, timeout=3600))
    py = str(dest / ".venv" / "Scripts" / "python.exe")
    steps.append(run([py, "-m", "unittest", "discover", "-s", "tests"], cwd=dest))
    steps.append(run([py, "scripts/setup/verify_layout.py"], cwd=dest))
    steps.append(run([py, "scripts/setup/doctor.py", "--mcp"], cwd=dest, timeout=600))
    tracked = subprocess.run(["git", "ls-files"], cwd=dest, capture_output=True, text=True).stdout.split()
    leaked = [f for f in tracked if f.startswith((".local", "runs/", "work/", ".venv")) or f.endswith((".trn", ".xml"))]
    print(json.dumps({"dest": str(dest), "ok": all(s["rc"] == 0 for s in steps) and not leaked,
                      "leaked_files": leaked, "steps": steps}, indent=1))


if __name__ == "__main__":
    main()
